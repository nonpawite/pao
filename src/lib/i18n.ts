const messages = { en, th }

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>) {
  let s: string = messages[locale][key]
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
  return s
}

/** Day of month for the cycle start picker: 1st, 2nd, 23rd; Thai uses the number alone. */
export function ordinal(locale: Locale, n: number) {
  if (locale === 'th') return String(n)
  const tens = n % 100
  const suffix = tens >= 11 && tens <= 13 ? 'th' : ['th', 'st', 'nd', 'rd'][n % 10] ?? 'th'
  return `${n}${suffix}`
}

const monthsEn = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']
const monthsTh = ['ม.ค.', 'ก.พ.', 'มี.ค.', 'เม.ย.', 'พ.ค.', 'มิ.ย.', 'ก.ค.', 'ส.ค.', 'ก.ย.', 'ต.ค.', 'พ.ย.', 'ธ.ค.']
const daysEn = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat']
const daysTh = ['อา.', 'จ.', 'อ.', 'พ.', 'พฤ.', 'ศ.', 'ส.']

/** Short weekday names, Monday first. */
export const weekdayNames = (locale: Locale) => [1, 2, 3, 4, 5, 6, 0].map((i) => (locale === 'th' ? daysTh : daysEn)[i])

/** '2026-10-16' to '16 Oct' / '16 ต.ค.'; with weekday: 'Fri 16 Oct'. */
export const monthNames = (locale: Locale) => (locale === 'th' ? monthsTh : monthsEn)

export function formatDay(locale: Locale, date: string, withWeekday = false) {
  const [y, m, d] = date.split('-').map(Number)
  const months = locale === 'th' ? monthsTh : monthsEn
  const wd = new Date(Date.UTC(y, m - 1, d)).getUTCDay()
  const base = `${d} ${months[m - 1]}`
  return withWeekday ? `${(locale === 'th' ? daysTh : daysEn)[wd]} ${base}` : base
}

